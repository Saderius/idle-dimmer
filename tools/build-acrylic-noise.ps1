# Embed Microsoft's original MIT-licensed PNG so the executable has no loose-texture dependency.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'icons/acrylic-noise.png'
$header = Join-Path $root 'AcrylicNoiseData.h'
if ((Test-Path $header) -and (Get-Item $header).LastWriteTimeUtc -ge (Get-Item $source).LastWriteTimeUtc) { exit 0 }
$bytes = [IO.File]::ReadAllBytes($source)
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tools/build-acrylic-noise.ps1 from icons/acrylic-noise.png.')
$lines.Add('// Copyright (c) Microsoft Corporation. MIT license: icons/acrylic-noise.LICENSE.txt.')
$lines.Add('#pragma once')
$lines.Add('namespace acrylicnoise {')
$lines.Add('static const unsigned char kPng[] = {')
for ($i = 0; $i -lt $bytes.Length; $i += 24) {
    $end = [Math]::Min($i + 23, $bytes.Length - 1)
    $row = ($bytes[$i..$end] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ','
    $lines.Add("    $row,")
}
$lines.Add('};')
$lines.Add('} // namespace acrylicnoise')
[IO.File]::WriteAllLines($header, $lines, [Text.UTF8Encoding]::new($false))
